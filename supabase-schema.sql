-- Aganze marketplace security and trust schema.
-- Run in Supabase SQL Editor on a new project, or migrate carefully in staging first.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'candidate' check (role in ('candidate','company')),
  headline text,
  bio text,
  location text,
  skills text[] not null default '{}',
  website text,
  company_name text,
  company_website text,
  is_public boolean not null default false,
  is_verified boolean not null default false,
  verification_status text not null default 'unverified' check (verification_status in ('unverified','pending','verified','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.simulations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 160),
  description text check (description is null or char_length(description) <= 5000),
  category text,
  file_path text,
  file_name text,
  evidence_url text,
  issuer_name text,
  completed_on date,
  verification_status text not null default 'pending' check (verification_status in ('pending','approved','rejected')),
  verification_notes text,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) <= 320),
  message text not null check (char_length(message) between 10 and 5000),
  created_at timestamptz not null default now()
);

create table if not exists public.contact_requests (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.profiles(id) on delete cascade,
  candidate_id uuid not null references public.profiles(id) on delete cascade,
  subject text not null check (char_length(subject) between 3 and 160),
  message text not null check (char_length(message) between 10 and 5000),
  status text not null default 'pending' check (status in ('pending','accepted','declined','closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (company_id <> candidate_id)
);

create table if not exists public.blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  reported_profile_id uuid references public.profiles(id) on delete cascade,
  reported_simulation_id uuid references public.simulations(id) on delete cascade,
  reason text not null check (char_length(reason) between 10 and 2000),
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now(),
  check (reported_profile_id is not null or reported_simulation_id is not null)
);

create index if not exists profiles_discovery_idx on public.profiles (role, is_public, verification_status, updated_at desc);
create index if not exists simulations_discovery_idx on public.simulations (user_id, is_public, verification_status, created_at desc);
create index if not exists requests_candidate_idx on public.contact_requests (candidate_id, status, updated_at desc);
create index if not exists requests_company_idx on public.contact_requests (company_id, status, updated_at desc);

create or replace function public.is_company() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'company' and is_verified = true);
$$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and verification_status = 'verified' and role = 'company' and company_name = 'Aganze Admin');
$$;

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists profiles_touch on public.profiles;
create trigger profiles_touch before update on public.profiles for each row execute function public.touch_updated_at();
drop trigger if exists simulations_touch on public.simulations;
create trigger simulations_touch before update on public.simulations for each row execute function public.touch_updated_at();
drop trigger if exists requests_touch on public.contact_requests;
create trigger requests_touch before update on public.contact_requests for each row execute function public.touch_updated_at();

-- Users cannot promote themselves, change roles, or mark evidence/company accounts as verified.
create or replace function public.protect_trust_fields() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    if tg_op = 'UPDATE' and (new.role <> old.role or new.is_verified <> old.is_verified or new.verification_status <> old.verification_status) then
      raise exception 'Trust and role fields can only be changed by an administrator';
    end if;
    new.role := case when tg_op = 'UPDATE' then old.role else coalesce(new.role, 'candidate') end;
    new.is_verified := case when tg_op = 'UPDATE' then old.is_verified else false end;
    new.verification_status := case when tg_op = 'UPDATE' then old.verification_status else 'unverified' end;
  end if;
  return new;
end; $$;
drop trigger if exists profiles_protect_trust on public.profiles;
create trigger profiles_protect_trust before insert or update on public.profiles for each row execute function public.protect_trust_fields();

