alter table public.contact_requests enable row level security;
alter table public.blocks enable row level security;
alter table public.reports enable row level security;

drop policy if exists "Profiles are publicly readable" on public.profiles;
drop policy if exists "Users can create their profile" on public.profiles;
drop policy if exists "Users can update their profile" on public.profiles;
drop policy if exists "Users can delete their profile" on public.profiles;
create policy profiles_select on public.profiles for select using (
  id = auth.uid() or (role = 'candidate' and is_public = true and verification_status in ('pending','verified') and public.is_company())
);
create policy profiles_insert on public.profiles for insert with check (auth.uid() = id);
create policy profiles_update on public.profiles for update using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());
create policy profiles_delete on public.profiles for delete using (id = auth.uid() or public.is_admin());

drop policy if exists "Users can manage their simulations" on public.simulations;
create policy simulations_owner on public.simulations for all using (user_id = auth.uid() or public.is_admin()) with check (user_id = auth.uid() or public.is_admin());
create policy simulations_discovery on public.simulations for select using (
  public.is_company() and is_public = true and verification_status = 'approved'
  and exists (select 1 from public.profiles p where p.id = simulations.user_id and p.role = 'candidate' and p.is_public = true)
);

create policy contact_messages_insert on public.contact_messages for insert with check (true);
create policy contact_messages_admin on public.contact_messages for select using (public.is_admin());

create policy requests_insert_company on public.contact_requests for insert with check (
  company_id = auth.uid() and public.is_company()
  and exists (select 1 from public.profiles p where p.id = candidate_id and p.role = 'candidate' and p.is_public = true)
  and not exists (select 1 from public.blocks b where b.blocker_id = candidate_id and b.blocked_id = auth.uid())
);
create policy requests_participants_read on public.contact_requests for select using (company_id = auth.uid() or candidate_id = auth.uid());
create policy requests_candidate_update on public.contact_requests for update using (candidate_id = auth.uid()) with check (candidate_id = auth.uid());
create policy requests_company_update on public.contact_requests for update using (company_id = auth.uid()) with check (company_id = auth.uid());

drop policy if exists "Users manage their own simulation files" on storage.objects;
create policy simulation_files_owner on storage.objects for all using (bucket_id = 'simulations' and auth.uid()::text = (storage.foldername(name))[1]) with check (bucket_id = 'simulations' and auth.uid()::text = (storage.foldername(name))[1]);
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values ('simulations', 'simulations', false, 10485760, array['application/pdf','image/png','image/jpeg','text/plain','application/zip']) on conflict (id) do update set public = false, file_size_limit = 10485760;

create policy blocks_owner on public.blocks for all using (blocker_id = auth.uid()) with check (blocker_id = auth.uid());
create policy reports_insert on public.reports for insert with check (reporter_id = auth.uid());
create policy reports_owner on public.reports for select using (reporter_id = auth.uid() or public.is_admin());
create policy reports_admin_update on public.reports for update using (public.is_admin()) with check (public.is_admin());

-- Only selected fields are exposed through this view for employer discovery.
create or replace view public.public_candidate_profiles with (security_invoker = true) as
select id, full_name, headline, bio, location, skills, website, is_verified, updated_at
from public.profiles
where role = 'candidate' and is_public = true and verification_status in ('pending','verified');
